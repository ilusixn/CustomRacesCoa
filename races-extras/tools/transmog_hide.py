"""Wardrobe appearances that show nothing ("No Pants", "No Boots" ...): empty-looking items + appearances.
   python transmog_hide.py client|server
client : reads the effective client tables (our own archive excluded) and writes Item / ItemDisplayInfo / Appearances /
         ItemAppearances to kv/out/client (build_client.py packs that folder)
server : reads the live realm tables and writes the four files to kv/out/server_extra (copy them into CoA-Repack/Data/dbc)
SQL    : kv/transmog_hide.sql (acore_world.item_template rows for the same items)."""
import os, sys
sys.path[:0] = [r'C:\CoA-Build\kv', r'C:\CoA-Build\esteria_racials']
import estlib, effread

BS = chr(92)
SIDE = sys.argv[1]
OUT = r'C:\CoA-Build\kv\out' + BS + ('client' if SIDE == 'client' else 'server_extra')
os.makedirs(OUT, exist_ok=True)
DISPLAY = 171201
BASE = 9800001
# (appearance category, inventory type, name)
PIECES = [(1, 1, 'No Helm'), (2, 3, 'No Shoulders'), (3, 16, 'No Cloak'), (4, 5, 'No Chest'), (7, 9, 'No Wrist Guards'),
          (8, 10, 'No Gloves'), (9, 6, 'No Belt'), (10, 7, 'No Pants'), (11, 8, 'No Boots')]


def load(name):
    if SIDE == 'client':
        return estlib.DBC(effread.read('DBFilesClient' + BS + name + '.dbc')[0])
    return estlib.DBC.file(r'C:\CoA-Repack\Data\dbc' + BS + name + '.dbc')


def save(name, table):
    open(OUT + BS + name + '.dbc', 'wb').write(table.bytes())


# the empty display: a plain pants display with every model, texture and geoset removed
D = load('ItemDisplayInfo')
assert not any(r[0] == DISPLAY for r in D.rows)
template = [r for r in D.rows if r[0] == 7090][0]
empty = D.add('')
row = list(template)
row[0] = DISPLAY
for i in (1, 2, 3, 4, 6, 15, 16, 17, 18, 19, 20, 21, 22):
    row[i] = empty
row[5] = D.add('INV_Misc_QuestionMark')
for i in (7, 8, 9, 10, 11, 12, 13, 14, 23, 24):
    row[i] = 0
D.rows.append(row)
save('ItemDisplayInfo', D)

I = load('Item')
A = load('Appearances')
IA = load('ItemAppearances')
next_item_appearance = max(r[0] for r in IA.rows) + 1
sql = ['-- generated by kv/transmog_hide.py: "No Pants" & friends (empty wardrobe appearances)']
for n, (category, inventory, name) in enumerate(PIECES):
    entry = BASE + n
    assert not any(r[0] == entry for r in I.rows) and not any(r[0] == entry for r in A.rows), entry
    I.rows.append([entry, 4, 0, 4294967295, 0, DISPLAY, inventory, 0])
    a = list(A.rows[0])
    a[0], a[1], a[3], a[8] = entry, entry, entry, entry
    a[5], a[6], a[7] = category, 0, 0
    A.rows.append(a)
    IA.rows.append([next_item_appearance + n, entry, entry])
    sql.append("DELETE FROM `item_template` WHERE `entry` = %d;" % entry)
    sql.append("INSERT INTO `item_template` (`entry`, `class`, `subclass`, `name`, `displayid`, `Quality`, `Flags`, `BuyCount`, "
               "`InventoryType`, `AllowableClass`, `AllowableRace`, `ItemLevel`, `RequiredLevel`, `maxcount`, `stackable`, `bonding`, "
               "`description`) VALUES (%d, 4, 0, '%s', %d, 1, 0, 1, %d, -1, -1, 1, 0, 1, 1, 0, 'Shows nothing on this slot.');"
               % (entry, name, DISPLAY, inventory))
save('Item', I)
save('Appearances', A)
save('ItemAppearances', IA)
if SIDE == 'server':
    open(r'C:\CoA-Build\kv\transmog_hide.sql', 'w').write('\n'.join(sql) + '\n')
print(SIDE, 'ok', len(PIECES), 'items from', BASE)
